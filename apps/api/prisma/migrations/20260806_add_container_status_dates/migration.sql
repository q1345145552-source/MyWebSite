-- 柜子记下每一步实际发生的日期
--
-- 柜子原来只有 departure_date（开船）和 ata（到港）两个日期字段，都是海运的。
-- 陆运的「到达凭祥口岸 / 出口放行 / 过境越南 / 老挝边境放行」走的哪天，系统没地方存。
--
-- 为什么现在要存：员工的实际操作是「货到泰国仓了才在系统里补建柜子」，然后把运单装进去。
-- 装进去时要给这票货补记它随柜走过的环节（见 loading-manifests 的随柜补记逻辑）；
-- 如果没有每一步的真实日期，补出来的时间只能在建柜时间和当前时间之间平摊 ——
-- 而这两个时间就差几分钟，补出来 9 条轨迹全落在同一分钟，等于假数据（实测过）。
--
-- 存成 JSON 文本，形如 {"SEALED":"2026-07-20T00:00:00.000Z","AT_PORT_CN":"..."}。
-- 只加一列、可空；老柜子是 NULL，补记时自动退回原来的平摊逻辑，不影响已有数据。

ALTER TABLE containers ADD COLUMN IF NOT EXISTS status_dates TEXT;
